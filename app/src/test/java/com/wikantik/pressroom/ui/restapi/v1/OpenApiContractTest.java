    /**
     * springdoc names a schema by its type's simple name, and two types with
     * one simple name are silently merged into whichever it met first. So no
     * two distinct types in the API's DTO and controller packages (nested
     * records included; test classes are not scanned), nor the problem body,
     * may share one.
     */
    @Test
    void noTwoApiTypesShareASimpleName() throws IOException, ClassNotFoundException {
        Map<String, Set<String>> byName = new TreeMap<>();
        List<String> roots = List.of(API_PACKAGE, EntryDtos.class.getPackageName());
        PathMatchingResourcePatternResolver resolver = new PathMatchingResourcePatternResolver();
        var mainClasses = EntriesApi.class.getProtectionDomain().getCodeSource();
        for (String root : roots) {
            String pattern = "classpath*:" + root.replace('.', '/') + "/*.class";
            for (Resource resource : resolver.getResources(pattern)) {
                String file = resource.getFilename();
                String binaryName = root + "." + file.substring(0, file.length() - ".class".length());
                if (binaryName.matches(".*\\$\\d+.*")) {
                    continue; // an anonymous or local class: never a schema
                }
                Class<?> type = Class.forName(binaryName, false, getClass().getClassLoader());
                if (type.getProtectionDomain().getCodeSource().equals(mainClasses)) {
                    byName.computeIfAbsent(schemaName(type), k -> new TreeSet<>()).add(type.getName());
                }
            }
        }
        for (Class<?> type : List.of(ApiProblem.class, ApiProblem.FieldError.class)) {
            byName.computeIfAbsent(schemaName(type), k -> new TreeSet<>()).add(type.getName());
        }
        assertTrue(byName.containsKey("EntryWrite") && byName.containsKey("EntriesApi"),
                "the scan found the API's types: " + byName.keySet());
        Map<String, Set<String>> clashes = new TreeMap<>();
        byName.forEach((name, types) -> {
            if (types.size() > 1) {
                clashes.put(name, types);
            }
        });
        assertEquals(Map.of(), clashes, "simple names shared by distinct API types");
    }

    /** The name springdoc gives a type's schema: its {@code @Schema} name, or its simple name. */
    private static String schemaName(Class<?> type) {
        io.swagger.v3.oas.annotations.media.Schema schema =
                type.getAnnotation(io.swagger.v3.oas.annotations.media.Schema.class);
        return schema != null && !schema.name().isEmpty() ? schema.name() : type.getSimpleName();
    }
