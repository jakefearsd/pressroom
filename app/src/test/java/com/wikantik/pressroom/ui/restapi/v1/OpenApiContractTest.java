    /**
     * A bare {@code object} with only {@code additionalProperties} gives a
     * generator a map of anything, which is how {@code ping}, {@code me} and
     * the maintenance actions used to read. None is left but the open request
     * body and the keyed dictionaries listed above.
     */
    @Test
    void noSchemaIsABareMapBeyondTheListedOnes() {
        List<String> bare = new ArrayList<>();
        operations().forEach((name, operation) -> {
            String id = operation.path("operationId").asString();
            for (String status : operation.get("responses").propertyNames()) {
                collectBareMaps(operation.get("responses").get(status), name + " " + status, bare);
            }
            operation.path("parameters").forEach(p -> collectBareMaps(p, name + " ?" + p.path("name").asString(), bare));
            JsonNode body = operation.path("requestBody");
            if (!body.isMissingNode()) {
                if (OPEN_MAP_BODIES.contains(id)) {
                    JsonNode schema = body.path("content").path("application/json").path("schema");
                    assertTrue(isBareMap(schema), id + " is listed as an open map: " + schema);
                    assertEquals("string", schema.path("additionalProperties").path("type").asString(),
                            id + " maps names to string values");
                } else {
                    collectBareMaps(body, name + " body", bare);
                }
            }
        });
        Set<String> dictionaries = new HashSet<>();
        for (String schemaName : schemas().propertyNames()) {
            JsonNode schema = schemas().get(schemaName);
            collectBareMaps(schema, schemaName, bare, true);
            JsonNode properties = schema.path("properties");
            for (String property : properties.propertyNames()) {
                String name = schemaName + "." + property;
                JsonNode member = properties.get(property);
                if (KEYED_DICTIONARIES.contains(name)) {
                    dictionaries.add(name);
                    JsonNode values = member.path("additionalProperties");
                    assertTrue(values.isObject() && !values.isEmpty(), name + " has a typed value: " + member);
                    assertFalse(member.path("description").asString("").isBlank(), name + " names its keys");
                } else {
                    collectBareMaps(member, name, bare);
                }
            }
        }
        assertEquals(KEYED_DICTIONARIES, dictionaries, "the listed dictionaries exist");
        assertEquals(List.of(), bare, "bare maps");
    }

    private static void collectBareMaps(JsonNode node, String where, List<String> bare) {
        collectBareMaps(node, where, bare, false);
    }

    /**
     * Bare maps in {@code node}. A component schema's own properties are
     * checked one by one by the caller, so {@code skipProperties} leaves them.
     */
    private static void collectBareMaps(JsonNode node, String where, List<String> bare, boolean skipProperties) {
        if (node == null || !node.isObject()) {
            return;
        }
        if (isBareMap(node)) {
            bare.add(where + ": " + node);
            return;
        }
        for (String key : node.propertyNames()) {
            if (skipProperties && "properties".equals(key)) {
                continue;
            }
            JsonNode child = node.get(key);
            if (child.isArray()) {
                child.forEach(c -> collectBareMaps(c, where + "/" + key, bare));
            } else {
                collectBareMaps(child, where + "/" + key, bare);
            }
        }
    }

    private static boolean isBareMap(JsonNode schema) {
        return "object".equals(schema.path("type").asString()) && schema.has("additionalProperties")
                && !schema.has("properties") && !schema.has("$ref");
    }

    /**
     * What a client author needs spelled out: the allowed values of every
     * enum, every member a request body takes (and the members of anything
     * nested in one), and every member a response promises.
     */
    @Test
    void enumsRequestBodyMembersAndRequiredMembersAreDescribed() {
        List<String> undescribed = new ArrayList<>();
        Set<String> bodies = new TreeSet<>();
        operations().forEach((name, operation) -> {
            operation.path("parameters").forEach(parameter -> {
                JsonNode schema = parameter.path("schema");
                if ((schema.has("enum") || schema.path("items").has("enum"))
                        && parameter.path("description").asString("").isBlank()) {
                    undescribed.add(name + " ?" + parameter.path("name").asString());
                }
            });
            collectRefs(operation.path("requestBody"), bodies);
        });
        assertTrue(bodies.containsAll(Set.of("EntryWrite", "TextEdit", "WeblogPatch")), "bodies found: " + bodies);
        for (String schemaName : schemas().propertyNames()) {
            JsonNode schema = schemas().get(schemaName);
            Set<String> required = strings(schema.path("required"));
            describedMembers(schema, schemaName, bodies.contains(schemaName), required, undescribed);
        }
        assertEquals(List.of(), undescribed, "members needing a description");
    }

    private static void describedMembers(JsonNode schema, String where, boolean body, Set<String> required,
                                         List<String> undescribed) {
        JsonNode properties = schema.path("properties");
        for (String property : properties.propertyNames()) {
            JsonNode member = properties.get(property);
            boolean isEnum = member.has("enum") || member.path("items").has("enum");
            if ((body || isEnum || required.contains(property))
                    && member.path("description").asString("").isBlank()) {
                undescribed.add(where + "." + property);
            }
            JsonNode nested = "array".equals(member.path("type").asString()) ? member.path("items") : member;
            if (nested.has("properties")) {
                describedMembers(nested, where + "." + property, body, strings(nested.path("required")),
                        undescribed);
            }
        }
    }

    /** Every component schema {@code node} reaches, transitively. */
    private static void collectRefs(JsonNode node, Set<String> found) {
        if (node == null) {
            return;
        }
        if (node.isObject()) {
            String ref = node.path("$ref").asString("");
            if (ref.startsWith("#/components/schemas/")) {
                String name = ref.substring(ref.lastIndexOf('/') + 1);
                if (found.add(name)) {
                    collectRefs(schemas().get(name), found);
                }
            }
            node.propertyNames().forEach(key -> collectRefs(node.get(key), found));
        } else if (node.isArray()) {
            node.forEach(child -> collectRefs(child, found));
        }
    }

    /**
     * Every list operation answers the one paging shape (Task 5, folded in
     * here): every operation taking a {@code limit} query parameter answers a
     * schema with {@code items} (or {@code entries} for the audit report,
     * which carries a tally), {@code offset}, {@code limit} and {@code
     * hasMore}, all required.
     */
    @Test
    void everyPagedOperationAnswersTheOneShape() {
        Set<String> seen = new HashSet<>();
        operations().forEach((name, operation) -> {
            if (!takesLimit(operation)) {
                return;
            }
            seen.add(name);
            assertPagedShape(name, operation);
        });
        assertTrue(seen.containsAll(Set.of("GET /v1/weblogs/{handle}/entries", "GET /v1/weblogs/{handle}/comments",
                "GET /v1/weblogs/{handle}/audit/seo", "GET /v1/weblogs", "GET /v1/admin/users",
                "GET /v1/weblogs/{handle}/media")), "the paged operations were found: " + seen);
    }

    /** One list operation against the paging shape; a failure names the operation and the shape it found. */
    private static void assertPagedShape(String name, JsonNode operation) {
        JsonNode responses = operation.path("responses");
        assertTrue(responses.has("200"), name + " has no 200 response, only " + responses.propertyNames()
                + ": " + responses);
        JsonNode declared = responses.get("200").path("content").path("application/json").path("schema");
        assertFalse(declared.isMissingNode(), name + "'s 200 declares no application/json schema: "
                + responses.get("200"));
        JsonNode schema = resolve(declared);
        assertTrue(schema != null, name + "'s 200 names a schema the document does not hold: " + declared);
        assertFalse("array".equals(schema.path("type").asString()), name + " answers a bare array: " + schema);
        JsonNode properties = schema.path("properties");
        assertTrue(properties.has("items") || properties.has("entries"),
                name + " answers neither items nor entries: " + schema);
        String list = properties.has("items") ? "items" : "entries";
        Set<String> required = strings(schema.path("required"));
        Set<String> wanted = new HashSet<>(PAGING);
        wanted.add(list);
        for (String member : wanted) {
            assertTrue(properties.has(member), name + " answers " + member + ": " + schema);
            assertTrue(required.contains(member), name + " marks " + member + " required: " + schema);
        }
        if (name.endsWith("/audit/seo")) {
            assertTrue(properties.has("entries"), name + " keeps entries, a report not a list");
        }
    }

    /**
     * An operation whose 200 is not the shape the check expects (none at all,
     * or a list under another name) fails naming the operation and what it
     * found, not with a null pointer or a member it never looked for.
     */
    @Test
    void anUnexpectedResponseShapeFailsNamingTheOperationAndTheShape() {
        ObjectMapper json = new ObjectMapper();
        JsonNode created = json.readTree("{\"responses\":{\"201\":{\"description\":\"made\"}}}");
        AssertionError noOk = assertThrows(AssertionError.class, () -> assertPagedShape("GET /v1/planted", created));
        assertTrue(noOk.getMessage().contains("GET /v1/planted") && noOk.getMessage().contains("201"),
                noOk.getMessage());

        JsonNode data = json.readTree("{\"responses\":{\"200\":{\"content\":{\"application/json\":{\"schema\":"
                + "{\"type\":\"object\",\"properties\":{\"data\":{\"type\":\"array\"}}}}}}}}");
        AssertionError noList = assertThrows(AssertionError.class, () -> assertPagedShape("GET /v1/planted", data));
        assertTrue(noList.getMessage().contains("GET /v1/planted") && noList.getMessage().contains("\"data\"")
                && noList.getMessage().contains("neither items nor entries"), noList.getMessage());
    }

    private static boolean takesLimit(JsonNode operation) {
        for (JsonNode parameter : operation.path("parameters")) {
            if ("limit".equals(parameter.path("name").asString()) && "query".equals(parameter.path("in").asString())) {
                return true;
            }
        }
        return false;
    }

