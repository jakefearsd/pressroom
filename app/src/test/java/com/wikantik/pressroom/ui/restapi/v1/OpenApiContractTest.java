    @Test
    void everyOperationAnswersATypedJsonBodyOrA204WithNone() {
        Map<String, JsonNode> operations = operations();
        assertEquals(OPERATION_IDS.size(), operations.size(), "one operation per pinned id: " + operations.keySet());
        for (Map.Entry<String, JsonNode> operation : operations.entrySet()) {
            String name = operation.getKey();
            JsonNode responses = operation.getValue().get("responses");
            List<String> successes = new ArrayList<>();
            for (String status : responses.propertyNames()) {
                if (status.startsWith("2")) {
                    successes.add(status);
                }
            }
            assertFalse(successes.isEmpty(), name + " documents a 2xx: " + responses);
            for (String status : successes) {
                JsonNode response = responses.get(status);
                if ("204".equals(status)) {
                    assertFalse(response.has("content"), name + ": a 204 has no body: " + response);
                    continue;
                }
                JsonNode content = response.path("content");
                assertEquals(List.of("application/json"), new ArrayList<>(content.propertyNames()),
                        name + " " + status + " is application/json: " + response);
                JsonNode schema = content.get("application/json").get("schema");
                assertTrue(isRef(schema) || "array".equals(schema.path("type").asString()) && isRef(schema.get("items")),
                        name + " " + status + " answers a named schema or an array of them: " + schema);
            }
        }
    }

    private static final Pattern PATH_TEMPLATE = Pattern.compile("\\{([^}/]+)}");

    /**
     * A typed client reads path parameters from the document: each {@code
     * {name}} of a path declares exactly one required {@code in: path}
     * parameter with a schema, and none is declared that the path lacks. The
     * action weblog's {@code {handle}} is resolved by an interceptor, not bound
     * to a method parameter, so springdoc cannot see it by itself.
     */
    @Test
    void everyPathTemplateVariableIsADeclaredRequiredPathParameter() {
        List<String> offenders = new ArrayList<>();
        operations().forEach((name, operation) -> {
            List<String> expected = new ArrayList<>();
            var matcher = PATH_TEMPLATE.matcher(name.substring(name.indexOf(' ') + 1));
            while (matcher.find()) {
                expected.add(matcher.group(1));
            }
            List<String> declared = new ArrayList<>();
            for (JsonNode parameter : operation.path("parameters")) {
                if ("path".equals(parameter.path("in").asString())) {
                    declared.add(parameter.path("name").asString());
                    if (!parameter.path("required").asBoolean(false) || !parameter.has("schema")
                            || !"string".equals(parameter.path("schema").path("type").asString())) {
                        offenders.add(name + ": " + parameter + " is not a required string path parameter");
                    }
                }
            }
            if (!new TreeSet<>(expected).equals(new TreeSet<>(declared)) || declared.size() != expected.size()) {
                offenders.add(name + ": template " + expected + " but declares " + declared);
            }
        });
        assertTrue(offenders.isEmpty(), offenders.size() + " offenders: " + offenders);
    }

    private static boolean isRef(JsonNode schema) {
        return schema != null && schema.path("$ref").asString("").startsWith("#/components/schemas/");
    }

    @Test
    void everyOperationDocumentsItsProblemsAsTheDefaultResponse() {
        for (Map.Entry<String, JsonNode> operation : operations().entrySet()) {
            JsonNode problem = operation.getValue().get("responses").path("default");
            assertFalse(problem.isMissingNode(), operation.getKey() + " has a default response");
            assertFalse(problem.path("description").asString("").isBlank(), operation.getKey());
            JsonNode content = problem.path("content");
            assertEquals(List.of("application/problem+json"), new ArrayList<>(content.propertyNames()),
                    operation.getKey() + ": " + problem);
            assertEquals(PROBLEM_REF, content.get("application/problem+json").path("schema").path("$ref").asString(),
                    operation.getKey());
        }
    }

    /**
     * {@code code} is a plain string, never an enum: a client generated
     * before a code was added must not refuse a body carrying it. The codes
     * known when the document was served ride along as {@code
     * x-extensible-enum}.
     */
    @Test
    void theProblemSchemaRequiresItsCoreMembersAndListsEveryCodeExtensibly() {
        JsonNode problem = schemas().get("ApiProblem");
        assertTrue(problem != null, "ApiProblem is a component schema");
        Set<String> required = strings(problem.path("required"));
        assertTrue(required.containsAll(Set.of("type", "title", "status", "code")), problem.toString());
        assertFalse(problem.path("description").asString("").isBlank(), "ApiProblem is described");
        JsonNode properties = problem.get("properties");
        for (var component : ApiProblem.class.getRecordComponents()) {
            JsonNode property = properties.get(component.getName());
            assertTrue(property != null, "ApiProblem documents " + component.getName());
            assertFalse(property.path("description").asString("").isBlank(),
                    "ApiProblem." + component.getName() + " is described");
        }
        JsonNode code = properties.get("code");
        assertEquals("string", code.path("type").asString(), code.toString());
        assertFalse(code.has("enum"), "code is not a closed enum: " + code);
        List<String> listed = new ArrayList<>();
        code.path("x-extensible-enum").forEach(c -> listed.add(c.asString()));
        Set<String> codes = new TreeSet<>();
        Arrays.stream(ProblemCode.values()).forEach(c -> codes.add(c.code()));
        assertEquals(codes, new TreeSet<>(listed), "x-extensible-enum lists every ProblemCode");
        assertEquals(codes.size(), listed.size(), "each code once");

        JsonNode fieldError = resolve(properties.get("errors").get("items"));
        assertFalse(fieldError.path("description").asString("").isBlank(), "the field error is described");
        assertEquals(codes, strings(fieldError.path("properties").path("code").path("x-extensible-enum")),
                "a field error's code lists the same codes");
        assertFalse(fieldError.path("properties").path("code").has("enum"));
    }

