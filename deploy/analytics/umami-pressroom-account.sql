-- Pressroom's own Umami account: an ordinary (role 'user', not admin)
-- login that can register websites and read their numbers, and nothing
-- else. Runs against the umami DATABASE after Umami's first boot has
-- created its "user" table (Umami 3.3.0's schema; see docs/dev/umami-api.md).
--
-- psql variables (never echoed; pass them, do not edit this file):
--   username  the account name, e.g. pressroom
--   pw        its password, kept in .env
--
-- Idempotent. A re-run with the same username updates the one row: a new
-- password (which also invalidates Umami tokens issued under the old one),
-- role back to 'user' if someone promoted it, and undeleted if Umami had
-- soft-deleted it. Every NOT NULL column without a default is supplied
-- (user_id, username, password, role); the rest default or stay NULL.
--
-- Umami verifies with bcrypt; pgcrypto's crypt(.., gen_salt('bf')) writes
-- a $2a$ hash, which Umami 3.3.0 accepts (UmamiApiContractTest).

CREATE EXTENSION IF NOT EXISTS pgcrypto;

INSERT INTO "user" (user_id, username, password, role)
VALUES (gen_random_uuid(), :'username', crypt(:'pw', gen_salt('bf')), 'user')
ON CONFLICT (username) DO UPDATE
    SET password   = EXCLUDED.password,
        role       = 'user',
        deleted_at = NULL,
        updated_at = now();
