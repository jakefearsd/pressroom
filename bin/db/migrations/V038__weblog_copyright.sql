-- Migration: a per-blog copyright notice, the first line of the site footer.
--
-- Plain text, at most 255 characters, edited on the blog's Settings screen
-- and over /api/v1. NULL (or blank, which is stored as NULL) means the
-- footer falls back to "(c) <year> <blog name>. All rights reserved." See
-- docs/superpowers/specs/2026-10-24-site-footer-design.md, "Copyright field".
--
-- Prerequisites: V002__baseline_schema (the weblog table).
--
-- Idempotent: safe to run on a database that already has it.

ALTER TABLE weblog ADD COLUMN IF NOT EXISTS copyright varchar(255);
